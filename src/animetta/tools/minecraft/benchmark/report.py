"""Markdown reporting helpers for Minecraft benchmark results."""

from __future__ import annotations

import time

from .models import BenchmarkMetrics


def generate_benchmark_report(results: dict[str, dict[str, BenchmarkMetrics]]) -> str:
    """Generate a markdown benchmark report."""
    lines: list[str] = []
    lines.append("# MC Bot Voyager Benchmark Report\n")
    lines.append(f"Generated: {time.strftime('%Y-%m-%d %H:%M:%S')}\n")

    lines.append("## Summary\n")
    lines.append(
        "| Scenario | Config | Completed | Time (s) | Items | Distance | "
        "Deaths | Skills Created | Task Rate |"
    )
    lines.append(
        "|----------|--------|-----------|----------|-------|----------|"
        "--------|----------------|-----------|"
    )

    for scenario_name, configs in results.items():
        for config_name, metrics in configs.items():
            status = "✅" if metrics.completed else "❌"
            lines.append(
                f"| {scenario_name} | {config_name} | {status} | "
                f"{metrics.elapsed_seconds:.0f} | {metrics.unique_items_collected} | "
                f"{metrics.distance_traveled:.0f} | {metrics.deaths} | "
                f"{metrics.skills_created} | {metrics.task_success_rate:.0%} |"
            )

    lines.append("\n## Detailed Results\n")
    for scenario_name, configs in results.items():
        lines.append(f"### {scenario_name}\n")
        best_config = max(
            configs.items(),
            key=lambda kv: (
                kv[1].completed,
                kv[1].task_success_rate,
                kv[1].unique_items_collected,
            ),
        )
        lines.append(
            f"**Best configuration:** {best_config[0]} "
            f"({'completed' if best_config[1].completed else 'not completed'}, "
            f"{best_config[1].task_success_rate:.0%} task success rate)\n"
        )

        lines.append("**Final Inventory (unique items):**\n")
        for config_name, metrics in configs.items():
            items_str = ", ".join(
                f"{item}×{count}"
                for item, count in sorted(metrics.final_inventory.items())
                if count > 0
            ) or "(empty)"
            lines.append(f"- `{config_name}`: {items_str}")
        lines.append("")

    lines.append("## Key Findings\n")
    all_metrics = [metrics for configs in results.values() for metrics in configs.values()]
    completed_count = sum(1 for metrics in all_metrics if metrics.completed)
    total_count = len(all_metrics)
    lines.append(
        f"- **Overall completion rate:** {completed_count}/{total_count} "
        f"({completed_count / total_count:.0%})\n"
    )

    mode_completions: dict[str, int] = {}
    for configs in results.values():
        for config_name, metrics in configs.items():
            if metrics.completed:
                mode_completions[config_name] = mode_completions.get(config_name, 0) + 1

    if mode_completions:
        best_mode = max(mode_completions, key=lambda key: mode_completions[key])
        lines.append(
            f"- **Most successful mode:** {best_mode} "
            f"({mode_completions[best_mode]} completions)\n"
        )

    total_skills = sum(
        metrics.skills_created for configs in results.values() for metrics in configs.values()
    )
    lines.append(f"- **Total skills created across all runs:** {total_skills}\n")

    total_deaths = sum(metrics.deaths for metrics in all_metrics)
    lines.append(f"- **Total deaths across all runs:** {total_deaths}\n")
    lines.append("\n---\n*Report generated by BenchmarkRunner*")
    return "\n".join(lines)
